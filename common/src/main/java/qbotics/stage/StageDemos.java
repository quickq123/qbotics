package qbotics.stage;

/**
 * The programs and notes the test stage puts on its computers. Each demo is short, uses the
 * stage's own device names, and prints what it did, so a feature can be tried by running
 * one file and changed by editing it.
 */
final class StageDemos {
    private StageDemos() {
    }

    static String readme(String mainAddress, String remoteAddress) {
        return String.join("\n",
                "THE TEST STAGE",
                "",
                "This computer is 'main' (" + mainAddress + "). Beside it, left to right:",
                "  store      an Interface: coal, logs, raw iron, ingots, then five open slots",
                "  chest      a Bus on a chest of coal, logs, raw iron, cobblestone, ingots",
                "  furnace    a Bus on a furnace",
                "  inbox      an Input on a barrel of redstone and gold",
                "  outbox     an Output on an empty barrel",
                "  tanks      a Fluid Interface;  big_tank  a Fluid Bus on a tank of water and lava",
                "  battery    an Energy Interface;  machine  an Energy Bus on a charged cell",
                "  xp         an Experience Interface holding 30 levels' worth",
                "  crafter    a Bus on a crafting table, which it works through the table's screen",
                "Behind them: lamp, a Logic Pin on a redstone lamp; placer and breaker, a Placer",
                "and a Breaker facing the same empty space from two sides.",
                "",
                "The other computer is 'remote' (" + remoteAddress + "), on its own cables and antenna.",
                "It is running demos/echo.py, which answers every message.",
                "",
                "Programs in demos/ (run one with:  run demos/1_items.py):",
                "  1_items.py     count, move into the furnace, collect what it made",
                "  2_filters.py   tags, wildcards, mods, and slots by number",
                "  3_fluid.py     move water and lava by name and by tank",
                "  4_energy.py    read and move energy",
                "  5_radio.py     list the other network, send a message, read the reply",
                "  6_devices.py   every device on this network",
                "  7_sources.py   sources and destinations: pools, keeping things back, exact amounts",
                "  8_crafting.py  open the crafting table's screen; planks by hand, sticks by Recipe",
                "  9_world.py     blink the lamp, place a block, break it again",
                "",
                "Other things to try from this terminal:",
                "  devices                      this network's devices",
                "  devices " + remoteAddress.substring(0, remoteAddress.indexOf(':')) + "          the other network's",
                "  ssh " + remoteAddress + "        log in to remote (Ctrl+C stops its echo; exit returns)",
                "  settings                     this computer's settings page",
                "",
                "Run /qbotics stage again, standing in the same place, to rebuild everything as it",
                "was. The computers get new, empty drives each time, so copy out anything of yours",
                "that you want to keep.",
                "");
    }

    static String remoteReadme(String mainAddress) {
        return String.join("\n",
                "This is 'remote', the second computer of the test stage.",
                "It runs demos/echo.py from the start: every message it gets, it sends back.",
                "Ctrl+C stops that. Start it again with:  run demos/echo.py",
                "The main computer is " + mainAddress + ".",
                "");
    }

    static final String ECHO = String.join("\n",
            "# Answers every message with the same data. Ctrl+C stops it.",
            "import network",
            "",
            "print('Echo: waiting for messages. Ctrl+C stops.')",
            "while True:",
            "    msg = network.receive()",
            "    print('from', msg.sender, ':', msg.data)",
            "    network.send(msg.sender, {'echo': msg.data})",
            "");

    /** File name and text of each demo on the main computer. */
    static String[][] forMain(String remoteAddress) {
        return new String[][] {
            {"1_items.py", String.join("\n",
                    "# Items: count, then move from a chest into a furnace and collect what it makes.",
                    "from logistics import network, move, Face",
                    "",
                    "net = network()",
                    "store = net.interface('store')",
                    "chest = net.bus('chest')",
                    "furnace = net.bus('furnace')",
                    "",
                    "print('The chest holds', chest.count(), 'items;', chest.count('coal'), 'are coal.')",
                    "",
                    "# move(from, to, what, how many). A furnace takes ore through its top and fuel",
                    "# through its sides, and gives what it has made at the bottom.",
                    "print('Raw iron, chest to furnace:', move(chest, furnace.destination(face=Face.TOP), 'raw_iron', 8))",
                    "print('Coal, chest to furnace:    ', move(chest, furnace.destination(face=Face.LEFT), 'coal', 2))",
                    "",
                    "# With nothing named, whatever is there moves: no need to know what was smelted.",
                    "print('Collected from the furnace:', move(furnace.source(face=Face.BOTTOM), store))",
                    "print('Smelting takes 10 seconds an item. Run this again to collect more.')",
                    "print('The store now holds', store.count('iron_ingot'), 'ingots.')",
                    "")},
            {"2_filters.py", String.join("\n",
                    "# Filters in place of names, and slots by number.",
                    "from logistics import network, move, Slot",
                    "",
                    "net = network()",
                    "store = net.interface('store')",
                    "chest = net.bus('chest')",
                    "",
                    "print('Logs of any kind (a tag):      ', chest.count('#minecraft:logs'))",
                    "print('Names ending in _log:          ', chest.count('*_log'))",
                    "print('From Minecraft, but not logs:  ', chest.count('@minecraft -*_log'))",
                    "print('Coal or cobblestone:           ', chest.count('coal | cobblestone'))",
                    "print('In the chest\\'s first slot:     ', chest.count(Slot(0)))",
                    "print('What is in each slot:')",
                    "for entry in chest.contents():",
                    "    print('  slot', entry['slot'], entry['count'], entry['item'])",
                    "",
                    "print('The store\\'s slot filters:', store.filters())",
                    "print('All the logs moved to the store:', move(chest, store, '#minecraft:logs'))",
                    "print('One log back, into slot 20:     ', move(store, chest.destination(slot=20), '#minecraft:logs', 1))",
                    "")},
            {"3_fluid.py", String.join("\n",
                    "# Fluid: amounts are millibuckets; 1000 is one bucket.",
                    "from logistics import network, move",
                    "",
                    "net = network()",
                    "tanks = net.fluid_interface('tanks')",
                    "big = net.fluid_bus('big_tank')",
                    "",
                    "print('The big tank holds:')",
                    "for tank in big.contents():",
                    "    print('  tank', tank['tank'], tank['amount'], 'of', tank['capacity'], tank['fluid'])",
                    "",
                    "print('Water moved in (3 buckets):   ', move(big, tanks, 'water', 3000))",
                    "print('Whatever is in its third tank:', move(big.source(slot=2), tanks))",
                    "print('Now storing', tanks.amount(), 'mB,', tanks.amount('water'), 'of it water.')",
                    "print('One bucket of water sent back:', move(tanks, big, 'water'))",
                    "")},
            {"4_energy.py", String.join("\n",
                    "# Energy, in FE (also called RF). It has no kinds, so only an amount is given.",
                    "from logistics import network, move",
                    "",
                    "net = network()",
                    "battery = net.energy_interface('battery')",
                    "machine = net.energy_bus('machine')",
                    "",
                    "print('The machine holds', machine.stored(), 'of', machine.capacity())",
                    "print('Drawn into the battery:', move(machine, battery, count=250000))",
                    "print('The battery now holds', battery.stored, 'of', battery.capacity)",
                    "print('Sent back:', move(battery, machine, count=100000))",
                    "")},
            {"5_radio.py", String.join("\n",
                    "# The other network: list it, send a message, read the reply.",
                    "import network",
                    "",
                    "REMOTE = '" + remoteAddress + "'    # the computer called remote",
                    "",
                    "me = network.ifconfig()",
                    "radio = network.Radio()",
                    "print('This computer is', me['external_ip'] + ':' + str(me['port']))",
                    "print('Its antenna is on frequency', radio.frequency, 'and its access is', radio.access)",
                    "",
                    "print('Devices behind the other antenna:')",
                    "for device in network.scan(REMOTE.split(':')[0]):",
                    "    print(' ', device['address'], device['kind'], device['name'])",
                    "",
                    "print('Sent:', network.send(REMOTE, {'hello': 'from main'}))",
                    "reply = network.receive(5)",
                    "if reply:",
                    "    print('Reply from', reply.sender, ':', reply.data)",
                    "else:",
                    "    print('No reply in 5 seconds. Is demos/echo.py running on remote?')",
                    "")},
            {"6_devices.py", String.join("\n",
                    "# Every device on this network, and how each is addressed.",
                    "from logistics import network",
                    "",
                    "for device in network().devices():",
                    "    print('%-22s %-14s %s %s' % (device.kind, device.ip, device.mac, device.name))",
                    "")},
            {"7_sources.py", String.join("\n",
                    "# Sources and destinations: described once, kept, pooled, and used by move().",
                    "from logistics import network, move, Face, NetworkError",
                    "",
                    "net = network()",
                    "store = net.interface('store')",
                    "chest = net.bus('chest')",
                    "furnace = net.bus('furnace')",
                    "inbox = net.input('inbox')",
                    "outbox = net.output('outbox')",
                    "",
                    "# A pool of places fuel can come from, tried in this order.",
                    "fuel = [",
                    "    store.source(only=['coal', 'charcoal']),",
                    "    chest.source(only='*coal'),",
                    "]",
                    "print('Fuel from the pool into the furnace:', move(fuel, furnace.destination(face=Face.LEFT), count=4))",
                    "",
                    "# Straight from one container to another, keeping the gold back.",
                    "print('Inbox to outbox, all but gold:', move(inbox.source(without='gold_ingot'), outbox))",
                    "",
                    "# need= moves exactly that many or nothing, and says so if it can't.",
                    "try:",
                    "    move(inbox, outbox, 'gold_ingot', need=50)",
                    "except NetworkError as problem:",
                    "    print('As expected:', problem)",
                    "print('Exactly 6 gold:', move(inbox, outbox, 'gold_ingot', need=6))",
                    "",
                    "# wait=True would pause here until the amount can be moved (Ctrl+C stops it):",
                    "#     move(fuel, furnace.destination(face=Face.LEFT), 'charcoal', need=8, wait=True)",
                    "")},
            {"8_crafting.py", String.join("\n",
                    "# Screens: a bus opens a block's screen as its owner would, and works its slots.",
                    "# A crafting table's slots exist only on its screen: 0 is the product, 1 to 9 the",
                    "# grid (hold the probe in Slots mode and open the table to see the numbers).",
                    "from logistics import network, Slot, Recipe",
                    "",
                    "net = network()",
                    "store = net.interface('store')",
                    "chest = net.bus('chest')",
                    "table = net.bus('crafter')",
                    "logs = [chest, store]    # wherever the logs are; demo 2 moves the chest's to the store",
                    "",
                    "# By hand. The with block closes the screen at the end, even after an error, and",
                    "# anything left in the grid goes back to an interface.",
                    "with table.open_screen() as screen:",
                    "    print('A log into the grid:', screen.put(Slot(5), 'oak_log', 1, sources=logs))",
                    "    for entry in screen.contents():",
                    "        print('  slot', entry['slot'], entry['count'], entry['item'])",
                    "    print('Planks taken out:', screen.take(Slot(0), store))",
                    "",
                    "# A recipe, filled in once: two planks, one above the other, make four sticks.",
                    "sticks = Recipe(sources=store, destination=store)",
                    "sticks.ingredient('oak_planks', Slot(2)).ingredient('oak_planks', Slot(5))",
                    "sticks.result(Slot(0), 'stick', 4)",
                    "runs = sticks.runs_for(8)",
                    "print('Runs the store can supply:', sticks.max_runs(), '  runs for 8 sticks:', runs)",
                    "if sticks.can_craft(runs):",
                    "    with table.open_screen() as screen:",
                    "        print('Made:', sticks.craft(runs, screen))",
                    "print('The store holds', store.count('stick'), 'sticks.')",
                    "")},
            {"9_world.py", String.join("\n",
                    "# World plates: a Logic Pin lights a lamp, a Placer puts a block down, a Breaker",
                    "# takes it back. The placer and breaker act as their owner would.",
                    "from logistics import network",
                    "",
                    "net = network()",
                    "store = net.interface('store')",
                    "chest = net.bus('chest')",
                    "lamp = net.pin('lamp')",
                    "placer = net.placer('placer')",
                    "breaker = net.breaker('breaker')",
                    "",
                    "# pulse() switches the lamp on for some ticks (20 a second) and off again by itself.",
                    "# The lamp lights at once; wait_for('block') then waits for the change it watches",
                    "# next: the lamp going out.",
                    "for n in range(3):",
                    "    lamp.pulse(10)",
                    "    lamp.wait_for('block', 2)",
                    "print('The lamp blinked three times.')",
                    "",
                    "print('Placed:', placer.place('cobblestone', sources=[store, chest]))",
                    "print('In front of the breaker:', breaker.block()['block'])",
                    "# Every drop must have somewhere to go, or the block isn't broken.",
                    "print('Broke it and got:', breaker.break_block(to=store))",
                    "")},
        };
    }
}
