    static String remoteReadme(String mainAddress) {
        return String.join("\n",
                "This is 'remote', the second computer of the test stage.",
                "It runs demos/echo.py from the start: every message it gets, it sends back.",
                "Ctrl+C stops that. Start it again with:  run demos/echo.py",
                "The main computer is " + mainAddress + ".",
                "");
    }

    static final String ECHO = String.join("\n",
            "# Answers every message with the same data. Ctrl+C stops it.",
            "import network",
            "",
            "print('Echo: waiting for messages. Ctrl+C stops.')",
            "while True:",
            "    msg = network.receive()",
            "    print('from', msg.sender, ':', msg.data)",
            "    network.send(msg.sender, {'echo': msg.data})",
            "");

